for (const scene of chishuiDraft.scenes) {
  const binding = campaignBindings[scene.id]
  if (!binding.eventId) continue
  const facts = scene.paragraphs.map(p => p.text)
  exhibitionDefinitions[binding.eventId] = {
    title: scene.title.split('——')[0]!.replace(/^第.章：/, ''), kind: 'battle', dateText: scene.metadata.split('｜')[0],
    opening: scene.title.split('——')[1]!, question: binding.direction + '，怎样回应此前的局势？',
    lead: facts[0]!, heroImageId: binding.imageIds.find(id => !['AST-0017','AST-0018'].includes(id)), imageIds: binding.imageIds,
    sections: [section('行动背景', facts.slice(0, 2), binding.sourceIds, binding.locator), section('渡河与后续行动', facts.slice(2), binding.sourceIds, binding.locator), section(scene.analysisTitle, scene.interpretation.map(p => p.text), binding.sourceIds, binding.locator, true)],
  }
}
