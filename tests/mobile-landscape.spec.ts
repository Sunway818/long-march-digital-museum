test('触摸协议单指平移、双指缩放、黄色跟随及关闭后手势恢复',async({browser})=>{
  const context=await browser.newContext({viewport:{width:844,height:390},hasTouch:true,isMobile:true})
  const page=await context.newPage();await page.goto('http://127.0.0.1:4173/#map')
  const map=page.locator('.history-map-canvas');await expect(map).toHaveAttribute('data-map-state','local')
  const cdp=await context.newCDPSession(page), box=(await map.boundingBox())!
  const x=box.x+box.width*.6,y=box.y+box.height*.65
  const center=await map.getAttribute('data-center')
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y,id:1}]})
  for(let i=1;i<=12;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+i*5,y,id:1}]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await expect.poll(()=>map.getAttribute('data-center')).not.toBe(center)
  const zoom=Number(await map.getAttribute('data-zoom'))
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:x-25,y,id:1},{x:x+25,y,id:2}]})
  for(let i=1;i<=10;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x-25-i*4,y,id:1},{x:x+25+i*4,y,id:2}]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await expect.poll(async()=>Number(await map.getAttribute('data-zoom'))).toBeGreaterThan(zoom+.3)
  // 双指松开后可能仍有惯性；等镜头稳定再选择实际可命中的节点。
  await expect.poll(async()=>{
    const before=(await map.getAttribute('data-center'))+'|'+(await map.getAttribute('data-zoom'))
    await page.waitForTimeout(160)
    return before===(await map.getAttribute('data-center'))+'|'+(await map.getAttribute('data-zoom'))
  }).toBe(true)
  const markerIndex=await page.locator('.history-marker').evaluateAll((nodes,b)=>nodes.findIndex(el=>{
    const r=el.getBoundingClientRect(),hit=document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)
    const single=(el.getAttribute('data-event-ids')??'').split(',').filter(Boolean).length===1
    return single&&!el.hasAttribute('hidden')&&r.x>b.x+60&&r.right<b.x+b.width-60&&r.y>b.y+48&&r.bottom<b.y+b.height-12&&hit?.closest('.history-marker')===el
  }),box)
  expect(markerIndex).toBeGreaterThanOrEqual(0)
  await page.locator('.history-marker').nth(markerIndex).tap()
  await expect(page.getByRole('button',{name:'深入了解'})).toBeVisible()
  await page.getByRole('button',{name:'收起资料面板'}).tap()
  await page.getByRole('button',{name:'部队与图例',exact:true}).tap()
  await page.getByRole('button',{name:'全部隐藏',exact:true}).click()
  await page.locator('.army-control input').nth(1).check()
  await page.getByRole('button',{name:'收起资料面板'}).tap()
  await page.getByRole('slider',{name:'全局历史日期'}).fill(String(toDay('1936-03-01')))
  const follow=page.getByRole('checkbox',{name:'镜头跟随',exact:true});await follow.scrollIntoViewIfNeeded();await follow.check()
  await expect(map).toHaveAttribute('data-follow-army','second')
  await follow.uncheck()
  expect(await page.evaluate(()=>scrollY)).toBe(0)
  await context.close()
})
