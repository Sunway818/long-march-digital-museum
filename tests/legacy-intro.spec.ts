import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const evidence = 'output/playwright/legacy-intro'
const prologue = (page: Page) => page.locator('#legacy-prologue')
const opacity = (page: Page, selector: string) => prologue(page).locator(selector).evaluate(el => Number(getComputedStyle(el).opacity))
const introState = (page: Page, state: string) => expect(prologue(page)).toHaveAttribute('data-intro', state)

for (const [width, height] of [[1440, 900], [844, 390], [740, 320]]) {
  test.describe(`首屏 ${width}×${height}`, () => {
    test.use({ viewport: { width, height }, isMobile: width < 1000, hasTouch: width < 1000 })

    test('五幕依次显现，暂停冻结进度，结束后可阅读和跨页重播', async ({page}, info) => {
      const prefix = `${evidence}/${info.project.name}-${width}`
      const errors: string[] = []
      page.on('pageerror', error => errors.push(error.message))
      page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
      await page.goto('/#legacy', { waitUntil: 'domcontentloaded' })
      const scene = prologue(page)
      const pause = page.getByRole('button', { name: '暂停光影' })
      await introState(page, 'playing')
      await expect(pause).toBeInViewport({ratio:.98})
      await expect.poll(() => opacity(page, '.legacy-mountain')).toBeGreaterThan(.35)
      expect(await opacity(page, '.legacy-campus-opening')).toBeLessThan(.12)
      expect(await opacity(page, '.legacy-title-glyph:first-child')).toBe(0)
      await page.screenshot({path: `${prefix}-01-history.png`})

      await expect.poll(() => opacity(page, '.legacy-campus-opening')).toBeGreaterThan(.06)
      await pause.click()
      await introState(page, 'paused')
      const readWipe = () => scene.locator('.legacy-campus-reveal').evaluate(el => getComputedStyle(el).maskPosition)
      const frozen = await readWipe()
      const frozenOpacity = await opacity(page, '.legacy-campus-opening')
      expect(frozen).not.toBe('0% 0%')
      await page.screenshot({path: `${prefix}-02-campus.png`})
      await page.waitForTimeout(280)
      expect(await readWipe()).toBe(frozen)
      expect(await opacity(page, '.legacy-campus-opening')).toBe(frozenOpacity)
      await page.getByRole('button', {name: '播放光影'}).click()
      await introState(page, 'playing')

      const glyphOpacity = () => scene.locator('.legacy-title-glyph').evaluateAll(nodes => nodes.map(node => Number(getComputedStyle(node).opacity)))
      await expect.poll(async () => { const [first, , , last] = await glyphOpacity(); return first > .25 && last < first }).toBe(true)
      await page.screenshot({path: `${prefix}-03-title.png`})
      const markerOpacity = () => scene.locator('.legacy-anniversaries > p').evaluateAll(nodes => nodes.map(node => Number(getComputedStyle(node).opacity)))
      await expect.poll(async () => { const [first, second] = await markerOpacity(); return first > .3 && second < first }).toBe(true)
      expect(await opacity(page, '.legacy-read-link')).toBe(0)
      await page.screenshot({path: `${prefix}-04-dates.png`})
      await expect.poll(() => opacity(page, '.legacy-read-link')).toBeGreaterThan(.5)
      await page.screenshot({path: `${prefix}-05-cue.png`})
      await introState(page, 'complete')
      expect(await scene.locator('.legacy-prologue-plate').evaluate(el => getComputedStyle(el).transform)).toBe('none')
      expect(await scene.locator('.legacy-campus-reveal').evaluate(el => getComputedStyle(el).maskImage)).toBe('none')
      await page.evaluate(() => document.fonts.ready)
      await page.screenshot({path: `${prefix}-06-complete.png`})
      expect(await scene.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)

      const ambient = () => scene.locator('.legacy-prologue-art').evaluate(el => getComputedStyle(el, ':after').animationPlayState)
      await pause.click()
      await expect.poll(ambient).toBe('paused')
      await page.getByRole('button', {name: '播放光影'}).click()
      await expect.poll(ambient).toBe('running')
      await introState(page, 'complete')
      await scene.getByRole('link', {name: '沿着精神之路，继续阅读'}).click()
      await expect(page.locator('#legacy-intro h2')).toBeFocused()
      await expect(page.locator('#legacy-intro h2')).toBeInViewport()
      await page.goBack()
      await introState(page, 'complete')
      await page.getByRole('navigation', {name: '精神传承导航'}).getByRole('link', {name: '英雄人物'}).click()
      await expect(page.locator('.people-memorial')).toBeVisible()
      await page.goBack()
      await introState(page, 'playing')
      await introState(page, 'complete')
      expect(errors).toEqual([])
    })
  })
}

test('深链、动态偏好切换和离开画面均直接收尾', async ({page}) => {
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/#legacy')
  await introState(page, 'complete')
  expect(await opacity(page, '.legacy-title-glyph:first-child')).toBe(1)
  await page.emulateMedia({reducedMotion:'no-preference'})
  await introState(page, 'complete')
  await page.goto('/#legacy/answer')
  await expect(page.locator('#legacy-answer-title')).toBeInViewport()
  await introState(page, 'complete')
  await page.goto('/#legacy')
  await introState(page, 'complete')
  await page.getByRole('navigation', {name:'精神传承导航'}).getByRole('link', {name:'首页',exact:true}).click()
  await page.goBack()
  await introState(page, 'playing')
  await page.locator('#legacy-relay').evaluate(el => el.scrollIntoView({block:'start'}))
  await introState(page, 'complete')
  await expect(page.locator('#legacy-relay h2')).toBeInViewport()
})
