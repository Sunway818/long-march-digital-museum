import { expect, test } from '@playwright/test'
import { archiveDrafts, archiveImages } from '../src/features/history-map/archiveContent'
import { eventById } from '../src/features/history-map/data'

test('一渡赤水独立草稿、双向影像关联与地图状态保留', async ({ page }, info) => {
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  expect(archiveDrafts['EVT-023']?.status).toBe('draft')
  expect(archiveImages(eventById.get('EVT-023')!).map(i => i.id)).toEqual(expect.arrayContaining(['AST-0017', 'AST-0033']))
  await page.goto('/#map')
  await expect(page.locator('.history-map-canvas')).toHaveAttribute('data-map-state', 'local')
  await page.getByRole('searchbox').fill('EVT-023')
  await page.locator('.history-event-list button').click()
  await expect.poll(async () => Number(await page.locator('.history-map-canvas').getAttribute('data-zoom'))).toBeGreaterThan(6)
  await page.waitForTimeout(900)
  const map = page.locator('.history-map-canvas')
  const canvasBefore = await page.locator('.maplibregl-canvas').elementHandle()
  const before = { center: await map.getAttribute('data-center'), zoom: await map.getAttribute('data-zoom'), day: await page.locator('.unified-timeline').getAttribute('data-current-day'), checked: await page.locator('.army-control input:checked').count() }
  await page.getByRole('button', { name: '深入了解' }).click()
  const archive = page.locator('.history-archive-dialog')
  await expect(archive).toBeVisible()
  await expect(archive.getByRole('heading', { name: '一渡赤水', exact: true })).toBeVisible()
  await expect(archive.locator('.exhibit-date time')).toHaveText('1935年1月29日')
  await expect(archive.locator('.exhibit-date time')).toHaveAttribute('datetime', '1935-01-29')
  await expect(archive.locator('.exhibit-review-label,.exhibit-review')).toHaveCount(0)
  await expect(archive.locator('.exhibit-opening-image figcaption')).toContainText('拍摄年代未注明')
  await expect(archive.locator('.exhibit-opening-image figcaption')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(archive.getByText('本站解读', { exact: true })).toBeVisible()
  await expect(archive.locator('.exhibit-image')).toHaveCount(2)
  await expect.poll(() => archive.locator('.exhibit-opening-image img').evaluate(el => (el as HTMLImageElement).naturalWidth)).toBeGreaterThan(100)
  const box = (await archive.boundingBox())!, width = page.viewportSize()!.width
  expect(box.width / width).toBeGreaterThan(.91)
  expect(box.width / width).toBeLessThanOrEqual(.93)
  expect(box.height / page.viewportSize()!.height).toBeGreaterThan(.91)
  await expect(archive.locator('.archive-sources')).not.toHaveAttribute('open', '')
  expect(await archive.locator('.chishui-exhibition').innerText()).not.toMatch(/EVT-\d|PLC-\d/)
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: `output/playwright/exhibition-refinement/${info.project.name}-opening.png` })
  await archive.locator('.exhibit-narrative').evaluate(el => el.scrollIntoView({ block: 'start' }))
  await page.screenshot({ path: `output/playwright/exhibition-refinement/${info.project.name}-narrative.png` })
  await archive.locator('.exhibit-route').scrollIntoViewIfNeeded()
  await expect.poll(() => archive.locator('.exhibit-route img').evaluate(el => (el as HTMLImageElement).naturalWidth)).toBeGreaterThan(100)
  await page.screenshot({ path: `output/playwright/exhibition-refinement/${info.project.name}-route.png` })
  await archive.locator('.exhibit-analysis').scrollIntoViewIfNeeded()
  await page.screenshot({ path: `output/playwright/exhibition-refinement/${info.project.name}-analysis.png` })
  await archive.locator('.exhibit-image-open').first().click()
  await expect(page.locator('.history-image-dialog')).toBeVisible()
  const viewer = page.locator('.exhibit-image-viewer')
  await expect(viewer.locator('.exhibit-viewer-stage img')).toHaveCSS('object-fit', 'scale-down')
  const imageBox = (await viewer.locator('.exhibit-viewer-stage img').boundingBox())!
  const stageBox = (await viewer.locator('.exhibit-viewer-stage').boundingBox())!
  expect(imageBox.height).toBeLessThanOrEqual(stageBox.height)
  await expect(viewer.getByRole('link', { name: '打开原始来源' })).toHaveCSS('color', 'rgb(216, 192, 145)')
  await expect(viewer.getByRole('heading')).toContainText('土城一渡赤水渡口')
  await expect(viewer.getByText('影像审核信息', { exact: true })).toHaveCount(0)
  await expect(viewer.locator('.exhibit-viewer-caption')).toContainText('拍摄年代未注明')
  await viewer.getByRole('button', { name: '下一张图片', exact: true }).click()
  await expect(viewer.getByRole('heading')).toContainText('要图')
  await viewer.getByRole('button', { name: '放大影像', exact: true }).click()
  await expect(viewer.locator('.exhibit-viewer-stage')).toHaveAttribute('data-zoomed', 'true')
  await viewer.getByRole('button', { name: '适应窗口', exact: true }).click()
  await viewer.locator('.exhibit-viewer-stage').focus()
  await page.keyboard.press('ArrowLeft')
  await expect(viewer.getByRole('heading')).toContainText('土城一渡赤水渡口')
  await page.screenshot({ path: `output/playwright/exhibition-refinement/${info.project.name}-image-viewer.png` })
  await page.keyboard.press('Escape')
  await expect(archive).toBeVisible()
  await expect(page.locator('.history-image-dialog')).toHaveCount(0)
  await expect(archive.locator('.exhibit-image-open').first()).toBeFocused()
  await archive.getByRole('button', { name: '下一个事件', exact: true }).click()
  await expect(archive.getByRole('heading', { name: '一渡赤水', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '返回地图', exact: true }).click()
  await expect(archive).toHaveCount(0)
  await expect(page.getByRole('button', { name: '深入了解' })).toBeFocused()
  expect(await map.getAttribute('data-center')).toBe(before.center)
  expect(await map.getAttribute('data-zoom')).toBe(before.zoom)
  expect(await page.locator('.unified-timeline').getAttribute('data-current-day')).toBe(before.day)
  expect(await page.locator('.army-control input:checked').count()).toBe(before.checked)
  await expect(page.locator('.maplibregl-canvas')).toHaveCount(1)
  expect(await page.locator('.maplibregl-canvas').evaluate((el, before) => el === before, canvasBefore)).toBe(true)
  expect(pageErrors).toEqual([])
  await info.attach('browser-environment', { body: JSON.stringify({ version: page.context().browser()?.version(), viewport: page.viewportSize(), platform: process.platform }), contentType: 'application/json' })
})

test('专题影像失败仍可阅读，减少动态效果及桌面缩窗保留返回入口', async ({ page }) => {
  await page.setViewportSize({ width: 960, height: 540 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.route('**/history-media/**', route => route.abort())
  await page.goto('/#map')
  await page.getByRole('group', { name: '地图资料面板' }).getByRole('button', { name: '历史资料', exact: true }).click()
  await page.getByRole('searchbox').fill('EVT-023')
  await page.locator('.history-event-list button').click()
  await page.getByRole('button', { name: '深入了解' }).click()
  const archive = page.locator('.history-archive-dialog')
  await expect(archive.locator('.exhibit-opening .exhibit-image-unavailable')).toBeVisible()
  await archive.getByRole('link', { name: '进入这段历史' }).click()
  await expect(archive.locator('#exhibit-story')).toBeFocused()
  const scroll = archive.locator('.archive-scroll')
  expect(await scroll.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await expect(archive.getByRole('button', { name: '关闭历史档案', exact: true })).toBeInViewport()
  await archive.getByRole('button', { name: '关闭历史档案', exact: true }).click()
  await expect(archive).toHaveCount(0)
})

