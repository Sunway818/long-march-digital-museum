test('一渡专题各展示模式均有影像，审阅参数仅控制审核信息', async ({ page }) => {
  await page.goto('/?review=0#map')
  const mediaRequests: string[] = []
  page.on('request', request => { if (request.url().includes('/history-media/')) mediaRequests.push(request.url()) })
  await page.getByRole('searchbox').fill('EVT-023')
  await page.locator('.history-event-list button').click()
  await page.getByRole('button', { name: '深入了解' }).click()
  const archive = page.locator('.history-archive-dialog')
  await expect(archive.locator('.exhibit-image')).toHaveCount(2)
  await expect(archive.locator('.exhibit-review')).toHaveCount(0)
  await expect(archive.locator('.exhibit-review-label')).toHaveCount(0)
  expect(await archive.innerText()).not.toMatch(/EVT-|PLC-/)
  expect(mediaRequests.length).toBeGreaterThan(0)
  await archive.locator('.archive-sources summary').click()
  expect(await archive.locator('.archive-sources a').count()).toBeGreaterThan(0)
  await page.keyboard.press('Escape')
  await page.goto('/?review=1#map')
  await page.getByRole('searchbox').fill('EVT-023')
  await page.locator('.history-event-list button').click()
  await page.getByRole('button', { name: '深入了解' }).click()
  await page.getByRole('button', { name: '查看出处 1', exact: true }).first().click()
  await expect(page.locator('.history-archive-dialog .archive-sources')).toHaveAttribute('open', '')
  await expect(page.locator('.history-archive-dialog [data-source]').first().locator('a')).toBeFocused()
  await expect(page.locator('.exhibit-review-label')).toHaveText('审阅预览')
  await page.locator('.exhibit-review summary').click()
  await expect(page.locator('.exhibit-review')).toContainText('公开展示许可均未确认')
})

test('专题路线图返回地图对照，保留地图实例、镜头、日期和筛选', async ({ page }) => {
  await page.goto('/#map')
  await expect(page.locator('.history-map-canvas')).toHaveAttribute('data-map-state', 'local')
  await page.getByRole('searchbox').fill('EVT-023')
  await page.locator('.history-event-list button').click()
  await expect.poll(async () => Number(await page.locator('.history-map-canvas').getAttribute('data-zoom'))).toBeGreaterThan(6)
  await page.waitForTimeout(900)
  const map = page.locator('.history-map-canvas')
  const canvas = await page.locator('.maplibregl-canvas').elementHandle()
  const before = { center: await map.getAttribute('data-center'), zoom: await map.getAttribute('data-zoom'), day: await page.locator('.unified-timeline').getAttribute('data-current-day'), armies: await page.locator('.army-control input').evaluateAll(inputs => inputs.map(i => (i as HTMLInputElement).checked)) }
  await page.getByRole('button', { name: '深入了解' }).click()
  const scroll = page.locator('.archive-scroll')
  const scrollBefore = await scroll.evaluate(el => el.scrollTop)
  await scroll.hover()
  await page.mouse.wheel(0, 600)
  await expect.poll(() => scroll.evaluate(el => el.scrollTop)).toBeGreaterThan(scrollBefore)
  await page.getByRole('button', { name: '返回地图对照', exact: true }).click()
  await expect(page.locator('.history-archive-dialog')).toHaveCount(0)
  await expect(page.locator('.history-marker[data-selected="true"]:not([hidden])').first()).toBeFocused()
  expect(await map.getAttribute('data-center')).toBe(before.center)
  expect(await map.getAttribute('data-zoom')).toBe(before.zoom)
  expect(await page.locator('.unified-timeline').getAttribute('data-current-day')).toBe(before.day)
  expect(await page.locator('.army-control input').evaluateAll(inputs => inputs.map(i => (i as HTMLInputElement).checked))).toEqual(before.armies)
  expect(await page.locator('.maplibregl-canvas').evaluate((el, previous) => el === previous, canvas)).toBe(true)
})
