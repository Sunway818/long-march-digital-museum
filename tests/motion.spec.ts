test('快速跨章、后台和运行中reduce中断无残留，地图时钟不追赶',async({page},info)=>{
 test.setTimeout(60_000)
 await page.setViewportSize({width:1440,height:900})
 await page.goto('/#map')
 await expect(page.locator('.history-map-canvas')).toHaveAttribute('data-map-state','local')
 await page.evaluate(()=>{location.hash='people'})
 await expect(page.locator('.people-memorial')).toBeVisible()
 await page.evaluate(()=>{location.hash='legacy'})
 await expect(page.locator('#legacy-title')).toBeVisible()
 const client=await page.context().newCDPSession(page)
 await client.send('HeapProfiler.collectGarbage')
 const before=await client.send('Runtime.getHeapUsage')
 const samples=[before]
 for(let index=0;index<24;index++){
  for(const hash of ['map','people','legacy/relay']){
   await page.evaluate(hash=>{location.hash=hash},hash)
   await expect(page.locator('.chapter-curtain')).toHaveAttribute('data-chapter',hash.split('/')[0]!)
  }
   if(index%8===7){await client.send('HeapProfiler.collectGarbage');samples.push(await client.send('Runtime.getHeapUsage'))}
 }
 await expect(page.locator('#legacy-relay')).toBeVisible()
 await page.evaluate(()=>{
  Object.defineProperty(document,'hidden',{configurable:true,value:true})
  document.dispatchEvent(new Event('visibilitychange'))
 })
 await expect(page.locator('html')).toHaveAttribute('data-motion-state','background')
 await expect(page.locator('.chapter-curtain')).toHaveCSS('opacity','0')
 expect(await page.locator('.people-flight-image').count()).toBe(0)
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'))})
 await page.emulateMedia({reducedMotion:'reduce'})
 await expect(page.locator('html')).toHaveAttribute('data-motion-state','reduced')
 await page.evaluate(()=>{location.hash='map'})
 await page.getByRole('button',{name:'时间演进',exact:true}).click()
 await page.getByRole('button',{name:'开始历史播放',exact:true}).click()
 await expect(page.getByRole('button',{name:'暂停历史播放',exact:true})).toBeVisible()
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'))})
 await expect(page.getByRole('button',{name:'开始历史播放',exact:true})).toBeVisible()
 const day=await page.locator('.unified-timeline').getAttribute('data-current-day')
 await page.waitForTimeout(300)
 await expect(page.locator('.unified-timeline')).toHaveAttribute('data-current-day',day!)
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'))})
 await expect(page.getByRole('button',{name:'开始历史播放',exact:true})).toBeVisible()
 await client.send('HeapProfiler.collectGarbage')
 const after=await client.send('Runtime.getHeapUsage')
 writeFileSync(`${evidence}/${info.project.name}-lifecycle.json`,JSON.stringify({visibility:'synthetic visibilitychange with document.hidden override',cycles:24,heapBefore:before,heapAfter:after,heapSamples:samples,delta:after.usedSize-before.usedSize,unfinishedClones:await page.locator('.people-flight-image').count(),historyDoesNotCatchUp:true},null,2))
})

