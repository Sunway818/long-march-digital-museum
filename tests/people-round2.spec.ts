test('环境光完整周期有可见差异，暂停冻结、恢复与聚焦反馈',async({page},info)=>{
  await page.goto('/#people')
  const root=page.locator('.people-memorial')
  await expect(root).toHaveAttribute('data-intro','done')
  const seek=async(time:number)=>page.locator('.people-environment').evaluate((el,value)=>{
    const animation=el.getAnimations({subtree:true}).find(a=>a instanceof CSSAnimation&&a.animationName==='people-gallery-light')
    if(!animation)throw Error('Ambient animation not found')
    animation.currentTime=value
  },time)
  await seek(0)
  const low=Number(await page.locator('.people-environment').evaluate(el=>getComputedStyle(el,':before').opacity))
  await page.screenshot({path:`output/playwright/people-round2/${info.project.name}-light-low.png`})
  await seek(8000)
  const high=Number(await page.locator('.people-environment').evaluate(el=>getComputedStyle(el,':before').opacity))
  expect(high-low).toBeGreaterThan(.5)
  await page.screenshot({path:`output/playwright/people-round2/${info.project.name}-light-high.png`})
  await page.getByRole('button',{name:'暂停环境光'}).click()
  const frozen=await page.locator('.people-environment').evaluate(el=>getComputedStyle(el,':before').opacity)
  await page.waitForTimeout(400)
  expect(await page.locator('.people-environment').evaluate(el=>getComputedStyle(el,':before').opacity)).toBe(frozen)
  await page.screenshot({path:`output/playwright/people-round2/${info.project.name}-light-paused.png`})
  await page.getByRole('button',{name:'播放环境光'}).click()
  await page.getByRole('link',{name:'阅读毛泽东人物档案'}).click()
  await expect(root).toHaveAttribute('data-focus','mao-zedong')
  await page.waitForTimeout(85)
  expect(Number(await page.locator('[data-person="zhou-enlai"]').evaluate(el=>getComputedStyle(el).opacity))).toBeLessThan(.65)
  await page.screenshot({path:`output/playwright/people-round2/${info.project.name}-light-focus.png`})
  await expect(root).toHaveAttribute('data-transition','idle')
})

test('地图直接双向导航，日期筛选画布和原视角保持',async({page},info)=>{
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/#map')
  const map=page.locator('.history-map-canvas')
  await expect(map).toHaveAttribute('data-map-state','local')
  const canvas=await page.locator('.maplibregl-canvas').elementHandle()
  await page.locator('.army-control input').nth(1).uncheck()
  await page.getByRole('slider',{name:'全局历史日期'}).fill(String(Math.floor(Date.parse('1935-06-01T00:00:00Z')/86400000)))
  await page.getByRole('button',{name:'放大地图',exact:true}).click()
  await page.waitForTimeout(500)
  const center=await map.getAttribute('data-center'),zoom=await map.getAttribute('data-zoom')
  const day=await page.locator('.unified-timeline').getAttribute('data-current-day')
  const before=await page.locator('.army-control input').evaluateAll(items=>items.map(el=>(el as HTMLInputElement).checked))
  await page.screenshot({path:`output/playwright/people-round2/${info.project.name}-map-entry.png`})
  await page.getByRole('navigation',{name:'地图导航'}).getByRole('link',{name:'英雄人物',exact:true}).click()
  await expect(page.locator('.people-portrait')).toHaveCount(16)
  await page.getByRole('link',{name:'时空长征',exact:true}).click()
  await expect(page.locator('.unified-timeline')).toHaveAttribute('data-current-day',day!)
  expect(await page.locator('.army-control input').evaluateAll(items=>items.map(el=>(el as HTMLInputElement).checked))).toEqual(before)
  expect(await canvas!.evaluate(el=>el===document.querySelector('.maplibregl-canvas'))).toBe(true)
  await expect(map).toHaveAttribute('data-center',center!)
  await expect(map).toHaveAttribute('data-zoom',zoom!)
})
