import {test,expect} from '@playwright/test'
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs'
import {createHash} from 'node:crypto'
import {memorialPeople} from '../src/data/history/people/people'
import {personSourceById} from '../src/data/history/people/sources'
import media from '../src/data/history/people/round2-media.json' with {type:'json'}

test('十六位长征档案内容、分期职务、关键瞬间与来源完整',()=>{
  mkdirSync('output/playwright/people-round2',{recursive:true})
  const stats=memorialPeople.map(person=>{
    const research=person.research!
    const text=[person.introduction,person.biography,...research.chapters.flatMap(c=>c.paragraphs),...research.moments.flatMap(m=>[m.context,m.action,m.result])].join('')
    const han=(text.match(/\p{Script=Han}/gu)??[]).length
    expect(han,person.name+' substantive Chinese characters').toBeGreaterThanOrEqual(800)
    expect(research.moments.length).toBeGreaterThanOrEqual(2)
    expect(research.moments.length).toBeLessThanOrEqual(4)
    expect(research.appointments.length).toBeGreaterThan(0)
    expect(research.basicSourceIds.every(id=>personSourceById.has(id))).toBe(true)
    return {id:person.id,name:person.name,han,moments:research.moments.length,lifespan:research.lifespan,portrait:person.portrait.id,status:person.publicationStatus}
  })
  writeFileSync('output/playwright/people-round2/content-audit.json',JSON.stringify(stats,null,2))
  for(const image of media){
    expect(createHash('sha256').update(readFileSync(image.localPath)).digest('hex')).toBe(image.sha256)
    expect(createHash('sha256').update(readFileSync('dist'+image.url)).digest('hex')).toBe(image.sha256)
  }
  expect(new Set(media.map(image=>image.url)).size).toBe(7)
})

